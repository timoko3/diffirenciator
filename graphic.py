import matplotlib.pyplot as plt
import numpy as np

# 1. Определение формулы (функции)
def my_formula(x):
    return x**2

# 2. Генерация данных
# Создаем массив значений X в определенном диапазоне (например, от -10 до 10)
x_values = np.linspace(-10, 10, 100) # 100 точек для гладкого графика

# Вычисляем соответствующие значения Y по формуле
y_values = my_formula(x_values)

# 3. Построение графика
plt.figure(figsize=(8, 6)) # Опционально: можно задать размер самого изображения графика
plt.plot(x_values, y_values, label='$y = x^2$') # label используется для легенды, $...$ для красивой формулы

# 4. Задание масштаба (диапазона осей)
# Задаем пределы для оси X (например, от -5 до 5)
plt.xlim(-5, 5)
# Задаем пределы для оси Y (например, от 0 до 30)
plt.ylim(0, 30)

# 5. Добавление элементов оформления (опционально)
plt.title('График функции с заданным масштабом') # Заголовок
plt.xlabel('Ось X') # Подпись оси X
plt.ylabel('Ось Y') # Подпись оси Y
plt.grid(True) # Включение сетки
plt.legend() # Включение легенды

# 6. Отображение графика
plt.show()
